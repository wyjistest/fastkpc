void adapter_require(bool okay,const char* message) {
  if(!okay) throw std::runtime_error(message);
}
__global__ void gather_residuals(const double* source,const int* ids,int n,int count,double* out) {
  const size_t i=size_t(blockIdx.x)*blockDim.x+threadIdx.x;
  if(i<size_t(n)*count) out[i]=source[size_t(ids[i/n])*n+i%n];
}
