struct StructuredDeleter { void operator()(void* p) const { if(p) adapter_structured_destroy(p); } };
struct AdapterEntry {
  enum State { Empty, Pending, ThreeFields, Resolved } state=Empty;
  int component_solver=0; // 1 structured-device-v1, 2 retained-dense-v1
  std::string residual_identity;
};
}
struct StructuredAdapterProbe {
  VerticalCallAccounting accounting;
  int n,k,count,capacity,device;
  size_t entry_values,vector_values;
  std::shared_ptr<FullCudaCiLegacyEigComponentCache> cache;
  std::unique_ptr<FullCudaCiLegacyEigExecutionContext> consumer;
  std::unique_ptr<TrackedDeviceBuffer> source,input,indices;
  std::unique_ptr<TrackedCudaEvent> input_ready,payload_ready;
  std::unique_ptr<void,StructuredDeleter> structured;
  StructuredDeviceView view{};
  std::vector<AdapterEntry> entries;
  std::vector<int> pending;
  std::vector<int> local_targets;
  std::vector<StructuredStatus> statuses;
  int mode=0;
  bool dense_failure=false;
  bool poisoned=false;

  StructuredAdapterProbe(int rows,int cols,int width,int batch,const double* residuals,
      const char* keys,int rotations):n(rows),k(cols),count(width),capacity(batch),
      entry_values(size_t(n)*k+k+2),vector_values(size_t(n)*k),entries(width) {
    adapter_require(n>=6 && k>=1 && k<=64 && count>0 && capacity>0 && capacity<=64 &&
      residuals && keys,"invalid adapter dimensions");
    check_cuda(cudaGetDevice(&device),"adapter current device");
    const size_t budget=size_t(std::max(count,2))*entry_values*sizeof(double);
    cache=create_full_cuda_ci_legacy_eig_component_cache(n,k,budget,true,capacity,
      4096,std::min(capacity,8));
    consumer=std::make_unique<FullCudaCiLegacyEigExecutionContext>(device,n,k,0,4096,0,&accounting);
    source=std::make_unique<TrackedDeviceBuffer>(size_t(n)*count*sizeof(double),&accounting);
    input=std::make_unique<TrackedDeviceBuffer>(size_t(n)*capacity*sizeof(double),&accounting);
    indices=std::make_unique<TrackedDeviceBuffer>(size_t(capacity)*sizeof(int),&accounting);
    input_ready=std::make_unique<TrackedCudaEvent>(true);
    payload_ready=std::make_unique<TrackedCudaEvent>(true);
    char error[512]={};
    structured.reset(adapter_structured_create(n,k,capacity,rotations,error));
    adapter_require(bool(structured),error);
    std::unordered_set<std::string> unique;
    for(int i=0;i<count;++i) {
      entries[i].residual_identity=std::string(keys+size_t(i)*64,64);
      adapter_require(is_lower_sha256(entries[i].residual_identity) &&
        unique.insert(entries[i].residual_identity).second,"invalid/duplicate residual identity");
      size_t slot=0;
      adapter_require(cache->reserve_slot(&slot) && slot==size_t(i),"cache reserve changed");
    }
    // Diagnostic fixture loading, outside the adapter's device-input boundary.
    check_cuda(cudaMemcpyAsync(source->get(),residuals,size_t(n)*count*sizeof(double),
      cudaMemcpyHostToDevice,cache->execution_context()->stream()),"load frozen GPU residual fixture");
    check_cuda(cudaStreamSynchronize(cache->execution_context()->stream()),"fixture ready");
  }
  ~StructuredAdapterProbe() {
    const ScopedPrefillDevice scope(device);
    if(consumer) (void)cudaStreamSynchronize(consumer->stream());
    if(cache) (void)cudaStreamSynchronize(cache->execution_context()->stream());
    structured.reset();
    consumer.reset(); cache.reset(); source.reset(); input.reset(); indices.reset();
    input_ready.reset(); payload_ready.reset();
  }
  void reset() {
    const ScopedPrefillDevice scope(device);
    check_cuda(cudaStreamSynchronize(consumer->stream()),"finish previous reader");
    check_cuda(cudaStreamSynchronize(cache->execution_context()->stream()),"finish previous producer");
    // Also joins a submit abandoned before finish; enqueue on the owner stream.
    if(!pending.empty() && mode==1) check_cuda(cudaEventSynchronize(view.complete),"abandon structured submit");
    pending.clear(); statuses.clear(); poisoned=false;
    for(auto& e:entries) { e.state=AdapterEntry::Empty; e.component_solver=0; }
  }
  void begin(const int* ids,int width,int selected_mode,int fault_index,int fault,int fail_dense) {
    const ScopedPrefillDevice scope(device);
    adapter_require(!poisoned && pending.empty(),"unfinished/failed adapter transaction");
    adapter_require(ids && width>0 && width<=capacity && (selected_mode==0 || selected_mode==1),
      "invalid adapter batch");
    std::unordered_set<int> unique;
    for(int i=0;i<width;++i) adapter_require(ids[i]>=0 && ids[i]<count &&
      unique.insert(ids[i]).second && entries[ids[i]].state==AdapterEntry::Empty,
      "duplicate/out-of-range/already-produced component");
    pending.assign(ids,ids+width); statuses.assign(width,{});
    for(int id:pending) entries[id].state=AdapterEntry::Pending;
    mode=selected_mode; dense_failure=fail_dense!=0;
    auto* c=cache->execution_context(); auto stream=c->stream();
    check_cuda(cudaMemcpyAsync(indices->get(),pending.data(),width*sizeof(int),
      cudaMemcpyHostToDevice,stream),"copy residual index metadata");
    gather_residuals<<<(size_t(n)*width+255)/256,256,0,stream>>>(
      static_cast<double*>(source->get()),static_cast<int*>(indices->get()),n,width,
      static_cast<double*>(input->get()));
    local_targets.resize(width); std::iota(local_targets.begin(),local_targets.end(),0);
    check_cuda(cudaMemcpyAsync(c->component_targets(),local_targets.data(),width*sizeof(int),
      cudaMemcpyHostToDevice,stream),"copy local target metadata");
    // Preserve the original total, without rebuilding it from structured mean*n^2.
    if(mode==1) {
      build_distance_rows_batch_kernel<<<dim3(n,width,1),kVerticalBlockSize,0,stream>>>(
        static_cast<double*>(input->get()),static_cast<int*>(c->component_targets()),n,width,
        size_t(n)*n,c->component_matrices(),c->row_sums());
      reduce_rows_batch_kernel<<<width,kVerticalBlockSize,0,stream>>>(c->row_sums(),n,width,c->totals());
    }
    check_cuda(cudaGetLastError(),"adapter residual/total kernels");
    check_cuda(cudaEventRecord(input_ready->get(),stream),"adapter input ready");
    if(mode==1) {
      char error[512]={};
      adapter_require(adapter_structured_submit(structured.get(),static_cast<double*>(input->get()),
        width,input_ready->get(),fault_index,fault,&view,error)==0,error);
    } else for(auto& s:statuses) s.reason=kDenseReference;
  }
  void store(int output_slot,int local_slot) {
    auto* c=cache->execution_context(); auto stream=c->stream();
    check_cuda(cudaMemcpyAsync(cache->vectors(output_slot),c->vectors()+size_t(local_slot)*vector_values,
      vector_values*sizeof(double),cudaMemcpyDeviceToDevice,stream),"D2D centered vectors");
    check_cuda(cudaMemcpyAsync(cache->selected_values(output_slot),c->selected_values()+size_t(local_slot)*k,
      k*sizeof(double),cudaMemcpyDeviceToDevice,stream),"D2D selected values");
    check_cuda(cudaMemcpyAsync(cache->total(output_slot),c->totals()+local_slot,sizeof(double),
      cudaMemcpyDeviceToDevice,stream),"D2D original total");
    check_cuda(cudaMemsetAsync(cache->self_moment(output_slot),0xff,sizeof(double),stream),
      "poison unresolved self moment");
  }
  void finish(StructuredStatus* output) {
    const ScopedPrefillDevice scope(device);
    adapter_require(!pending.empty() && !poisoned,"no live adapter transaction");
    auto* c=cache->execution_context(); auto stream=c->stream();
    const int width=pending.size();
    try {
      if(mode==1) {
        check_cuda(cudaStreamWaitEvent(stream,view.complete,0),"join structured producer");
        check_cuda(cudaMemcpyAsync(statuses.data(),view.status,width*sizeof(StructuredStatus),
          cudaMemcpyDeviceToHost,stream),"compact structured status only");
        check_cuda(cudaEventRecord(c->completion(),stream),"status checkpoint");
        check_cuda(cudaEventSynchronize(c->completion()),"wait bounded batch status");
        center_structured<<<width,kVerticalBlockSize,0,stream>>>(view.vectors,view.status,n,k,width,c->vectors());
        check_cuda(cudaGetLastError(),"center selected structured vectors");
        for(int i=0;i<width;++i) if(statuses[i].reason==kNoFallback) {
          check_cuda(cudaMemcpyAsync(c->selected_values()+size_t(i)*k,view.values+size_t(i)*(k+1),
            k*sizeof(double),cudaMemcpyDeviceToDevice,stream),"copy k selected structured values");
          store(pending[i],i);
        }
      }
      std::vector<int> fallback;
      for(int i=0;i<width;++i) if(statuses[i].reason) fallback.push_back(i);
      if(!fallback.empty()) {
        check_cuda(cudaMemcpyAsync(c->component_targets(),fallback.data(),fallback.size()*sizeof(int),
          cudaMemcpyHostToDevice,stream),"dense fallback indices only");
        submit_legacy_three_fields(c,static_cast<double*>(input->get()),n,k,fallback.size());
        std::vector<int> info(fallback.size(),-1);
        check_cuda(cudaMemcpyAsync(info.data(),c->solver_info(),info.size()*sizeof(int),
          cudaMemcpyDeviceToHost,stream),"compact dense fallback status");
        check_cuda(cudaEventRecord(c->completion(),stream),"dense fallback checkpoint");
        check_cuda(cudaEventSynchronize(c->completion()),"wait dense fallback status");
        if(dense_failure) info[0]=-92; // error-cleanup injection, not solver policy
        adapter_require(std::all_of(info.begin(),info.end(),[](int x){return x==0;}),
          "dense fallback failed closed; no batch entry published");
        for(size_t i=0;i<fallback.size();++i) store(pending[fallback[i]],i);
      }
      check_cuda(cudaEventRecord(payload_ready->get(),stream),"three-field D2D completion");
      for(int i=0;i<width;++i) {
        entries[pending[i]].state=AdapterEntry::ThreeFields;
        entries[pending[i]].component_solver=statuses[i].reason ? 2 : 1;
        if(output) output[i]=statuses[i];
      }
      pending.clear();
    } catch(...) { poisoned=true; throw; }
  }
  void require_entry(int id,AdapterEntry::State state) const {
    adapter_require(!poisoned && id>=0 && id<count && entries[id].state==state,
      "component unfinished, unresolved, or transaction failed");
  }
  void resolve(const int* ids,int width) {
    const ScopedPrefillDevice scope(device);
    adapter_require(width>0 && width<=capacity,"invalid original Gram group");
    std::unordered_set<int> unique;
    for(int i=0;i<width;++i) {
      require_entry(ids[i],AdapterEntry::ThreeFields);
      adapter_require(unique.insert(ids[i]).second,"duplicate Gram group identity");
    }
    auto* c=cache->execution_context(); auto stream=c->stream();
    for(int i=0;i<width;++i) {
      check_cuda(cudaMemcpyAsync(c->vectors()+size_t(i)*vector_values,cache->vectors(ids[i]),
        vector_values*sizeof(double),cudaMemcpyDeviceToDevice,stream),"gather original delayed Gram vectors");
      check_cuda(cudaMemcpyAsync(c->selected_values()+size_t(i)*k,cache->selected_values(ids[i]),
        k*sizeof(double),cudaMemcpyDeviceToDevice,stream),"gather original delayed Gram values");
    }
    submit_legacy_gram(c,n,k,width);
    for(int i=0;i<width;++i) {
      check_cuda(cudaMemcpyAsync(cache->self_moment(ids[i]),c->self_moments()+i,sizeof(double),
        cudaMemcpyDeviceToDevice,stream),"store delayed self moment");
      entries[ids[i]].state=AdapterEntry::Resolved;
    }
    check_cuda(cudaEventRecord(payload_ready->get(),stream),"delayed Gram ready");
  }
  void pairs(const int* left,const int* right,const unsigned long long* ids,int pair_count,void* output) {
    const ScopedPrefillDevice scope(device);
    adapter_require(pair_count>0 && pair_count<=4096,"pair capacity exceeded");
    for(int j=0;j<pair_count;++j) {
      require_entry(left[j],AdapterEntry::Resolved); require_entry(right[j],AdapterEntry::Resolved);
    }
    auto* execution_context=consumer.get(); const auto stream=execution_context->stream();
    check_cuda(cudaStreamWaitEvent(stream,payload_ready->get(),0),"consumer waits complete payload");
    const int num_col=k; const size_t pair_size=pair_count,cross_stride=size_t(k)*k;
    FixedSpBatchHostView batch; batch.n=n;
    std::vector<std::uintptr_t> metadata(10*pair_size);
    for(int j=0;j<pair_count;++j) {
      metadata[j]=ids[j];
      metadata[pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->vectors(left[j]));
      metadata[2*pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->vectors(right[j]));
      metadata[3*pair_size+j]=reinterpret_cast<std::uintptr_t>(execution_context->pair_cross()+j*cross_stride);
      metadata[4*pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->selected_values(left[j]));
      metadata[5*pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->selected_values(right[j]));
      metadata[6*pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->total(left[j]));
      metadata[7*pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->total(right[j]));
      metadata[8*pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->self_moment(left[j]));
      metadata[9*pair_size+j]=reinterpret_cast<std::uintptr_t>(cache->self_moment(right[j]));
    }
    check_cuda(cudaMemcpyAsync(execution_context->pair_metadata(),metadata.data(),
      metadata.size()*sizeof(std::uintptr_t),cudaMemcpyHostToDevice,stream),"original pair metadata");
    const double one=1.0,zero=0.0;
#include "pair_stage.inc"
    std::vector<DeviceCompactCiResult> results(pair_count);
    check_cuda(cudaMemcpyAsync(results.data(),execution_context->device_results(),
      pair_size*sizeof(DeviceCompactCiResult),cudaMemcpyDeviceToHost,stream),"compact GPU pair results");
    check_cuda(cudaEventRecord(execution_context->completion(),stream),"GPU pair ready");
    check_cuda(cudaEventSynchronize(execution_context->completion()),"read GPU pair compact result");
    for(const auto& r:results) adapter_require(r.status==kDcovStatusOk,
      "GPU pair/gamma failed closed; no results published");
    std::memcpy(output,results.data(),results.size()*sizeof(DeviceCompactCiResult));
  }
  void shadow(const int* ids,int width,double* output,int* solvers) {
    const ScopedPrefillDevice scope(device);
    auto stream=cache->execution_context()->stream();
    for(int i=0;i<width;++i) {
      adapter_require(!poisoned && ids[i]>=0 && ids[i]<count &&
        entries[ids[i]].state>=AdapterEntry::ThreeFields,"unfinished diagnostic shadow");
      check_cuda(cudaMemcpyAsync(output+size_t(i)*entry_values,cache->vectors(ids[i]),
        entry_values*sizeof(double),cudaMemcpyDeviceToHost,stream),"explicit diagnostic payload shadow");
      solvers[i]=entries[ids[i]].component_solver;
    }
    check_cuda(cudaStreamSynchronize(stream),"diagnostic payload ready");
  }
};
}

static thread_local char last_error[512];
template<class F> int guarded(F f) {
  try { f(); last_error[0]=0; return 0; }
  catch(const std::exception& e) { std::snprintf(last_error,sizeof(last_error),"%s",e.what()); return 1; }
}
extern "C" const char* adapter_error() { return last_error; }
extern "C" void* adapter_create(int n,int k,int count,int capacity,const double* residuals,
    const char* keys,int rotations) {
  void* p=nullptr; guarded([&]{p=new fastkpc::StructuredAdapterProbe(n,k,count,capacity,residuals,keys,rotations);}); return p;
}
extern "C" int adapter_begin(void* p,const int* ids,int count,int mode,int fault_index,int fault,int fail_dense) {
  return guarded([&]{static_cast<fastkpc::StructuredAdapterProbe*>(p)->begin(ids,count,mode,fault_index,fault,fail_dense);});
}
extern "C" int adapter_finish(void* p,StructuredStatus* status) {
  return guarded([&]{static_cast<fastkpc::StructuredAdapterProbe*>(p)->finish(status);});
}
extern "C" int adapter_reset(void* p) { return guarded([&]{static_cast<fastkpc::StructuredAdapterProbe*>(p)->reset();}); }
extern "C" int adapter_resolve(void* p,const int* ids,int count) {
  return guarded([&]{static_cast<fastkpc::StructuredAdapterProbe*>(p)->resolve(ids,count);});
}
extern "C" int adapter_pairs(void* p,const int* left,const int* right,const unsigned long long* ids,int count,void* out) {
  return guarded([&]{static_cast<fastkpc::StructuredAdapterProbe*>(p)->pairs(left,right,ids,count,out);});
}
extern "C" int adapter_shadow(void* p,const int* ids,int count,double* out,int* solvers) {
  return guarded([&]{static_cast<fastkpc::StructuredAdapterProbe*>(p)->shadow(ids,count,out,solvers);});
}
extern "C" void adapter_destroy(void* p) { delete static_cast<fastkpc::StructuredAdapterProbe*>(p); }
extern "C" int adapter_snapshot(long long* out) {
  const auto s=fastkpc::full_cuda_ci_vertical_resource_snapshot();
  out[0]=s.live_device_allocations; out[1]=s.live_device_bytes; out[2]=s.live_streams; out[3]=s.live_events;
  return 0;
}
extern "C" size_t adapter_workspace(void* p) {
  return adapter_structured_bytes(static_cast<fastkpc::StructuredAdapterProbe*>(p)->structured.get());
}
